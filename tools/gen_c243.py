SETTLED_LOGS = '/path/to/ultimate-bug-war-coop/logs'


def settled_points():
    """Every pawn rest point the drive has measured: `standing, N uu at (x, y, z)` rows of all drive logs."""
    import glob
    rx = re.compile(r'standing, \d+ uu at \((-?\d+), (-?\d+), (-?\d+)\)')
    pts = set()
    for path in glob.glob(SETTLED_LOGS + '/*.drive'):
        with open(path, encoding='utf-8', errors='replace') as f:
            pts.update(tuple(map(int, m)) for m in rx.findall(f.read()))
    return pts


LIFT = 30  # a warp onto a measured rest point lands this far above it (senior r6: no client fall over about 300 uu)


def settle_stands(text):
    """Run 5 void (nest A, 161 uu): a point warp lands at the given z and the pawn falls to the floor, so a 3D
    `wait stand` on the warp z never holds. Senior r6: each `wait stand x y z` with a measured rest point within
    25 uu in x y takes that z (3D check); with none it checks x y only (z `any`, the row logs the settled point).
    Each point warp more than 300 uu above its measured rest z goes to rest z + LIFT instead.
    Returns the text and the counts."""
    pts = settled_points()
    n = {'3d': 0, 'xy': 0, 'lowered': 0}
    unproven = set()

    def rest(x, y, r=25):
        near = [q for q in pts if abs(q[0] - x) <= r and abs(q[1] - y) <= r]
        return min(near, key=lambda q: abs(q[0] - x) + abs(q[1] - y))[2] if near else None

    def fix_stand(m):
        x, y = int(m.group(2)), int(m.group(3))
        sz = rest(x, y)
        n['3d' if sz is not None else 'xy'] += 1
        if sz is None:
            unproven.add((x, y))
        return f'{m.group(1)}wait stand {x} {y} {"any" if sz is None else sz} '

    def fix_warp(m):
        x, y, z = int(m.group(2)), int(m.group(3)), int(m.group(4))
        sz = rest(x, y, 100)  # a warp lowers on the floor of a rest point within 100 uu (C_51 client far: 71 uu)
        if sz is None or z - sz <= 300:
            return m.group(0)
        n['lowered'] += 1
        return f'{m.group(1)}point {x} {y} {sz + LIFT}'
    text = re.sub(r'((?:host|client) )wait stand (-?\d+) (-?\d+) (-?\d+) ', fix_stand, text)
    text = re.sub(r'(warp (?:actor|client) )point (-?\d+) (-?\d+) (-?\d+)', fix_warp, text)
    return text, n, sorted(unproven)


