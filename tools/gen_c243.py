    stand_r = SPAWN_STAND_R if spawner else STAND_R
    text = (f'host warp actor point {hx} {hy} {hz}\n'
            f'host warp client point {cx} {cy} {cz}\n'
            f'host wait stand {hx} {hy} {hz} {stand_r} timeout=15\n'
            f'client wait stand {cx} {cy} {cz} {stand_r} timeout=15\n')
