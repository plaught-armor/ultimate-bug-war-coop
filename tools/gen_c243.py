def done_rx(role, i):
    """A completion of objective i on role's log: the card049 row (host sent / client replayed) or the card097
    subsystem ObjectiveComplete line (cascades log only the latter, card 241 run 1)."""
    row = 'host sent' if role == 'host' else 'client t=\\d+ replayed'
    return (f'(?:card049: {row} Complete\\w*Objective\\((?:\\w+, )?{i}\\)'
            f'|card097: {role} t=\\d+ subsystem ObjectiveComplete\\({i}\\))')


def DONE(i):
    return done_rx('host', i)


def ADDED(i):
    """The host's own Add row (run 6: the `host sent` row can be missing, run 5 Satcom_SO2, card 262). i in either
    slot: a parent with lettered children (Resort_SO4) is only ever added as `AddSubObjective(Resort_SO4, ..._A)`."""
