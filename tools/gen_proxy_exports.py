#!/usr/bin/env python3
"""Generate the dwmapi.dll proxy export list from a reference dwmapi.dll.

Reads `llvm-readobj --coff-exports <dll>` and writes:
  mod/src/dwmapi.def                     LIBRARY/EXPORTS with the same ordinals (+NONAME)
  mod/src/proxy_exports.generated.inc    X-macro rows: UBW_EXPORT(index, ordinal, name-or-nullptr)

The reference is the dwmapi.dll that actually runs under our Proton (GE-Proton11-11).
Forwarded exports in the reference are rejected (none expected).

Run with `python3 -I tools/gen_proxy_exports.py [--dll PATH]`. Exit status != 0 on failure.
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DEFAULT_DLL = Path.home() / (".local/share/Steam/compatibilitytools.d/GE-Proton11-11-x86_64/"
                             "files/lib/wine/x86_64-windows/dwmapi.dll")
OUT_DEF = REPO / "mod/src/dwmapi.def"
OUT_INC = REPO / "mod/src/proxy_exports.generated.inc"

RE_ORD = re.compile(r"^\s*Ordinal: (\d+)\s*$")
RE_NAME = re.compile(r"^\s*Name: ?(\S*)\s*$")
RE_FWD = re.compile(r"^\s*ForwardedTo: ")
RE_CIDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
MAX_EXPORTS = 4096


def die(msg):
    print(f"gen_proxy_exports: error: {msg}", file=sys.stderr)
    sys.exit(1)


def read_exports(dll):
    try:
        res = subprocess.run(["llvm-readobj", "--coff-exports", str(dll)],
                             check=False, capture_output=True, text=True)
    except OSError as e:
        die(f"cannot run llvm-readobj: {e}")
    if res.returncode != 0:
        die(f"llvm-readobj exited {res.returncode}: {res.stderr.strip()}")
    exports = []
    ordinal = None
    for line in res.stdout.splitlines():
        if RE_FWD.match(line):
            die(f"ordinal {ordinal} is a forwarder; not supported")
        m = RE_ORD.match(line)
        if m:
            ordinal = int(m.group(1))
            continue
        m = RE_NAME.match(line)
        if m and ordinal is not None:
            name = m.group(1) or None
            if name is not None and not RE_CIDENT.match(name):
                die(f"export name {name!r} is not a plain identifier")
            exports.append((ordinal, name))
            ordinal = None
    if not exports or len(exports) > MAX_EXPORTS:
        die(f"implausible export count {len(exports)}")
    ords = [o for o, _ in exports]
    if len(set(ords)) != len(ords):
        die("duplicate ordinals")
    names = [n for _, n in exports if n]
    if len(set(names)) != len(names):
        die("duplicate names")
    return sorted(exports)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dll", type=Path, default=DEFAULT_DLL)
    a = ap.parse_args()
    exports = read_exports(a.dll)

    deflines = ["; GENERATED by tools/gen_proxy_exports.py -- do not edit.",
                f"; Reference: {a.dll}", "LIBRARY dwmapi", "EXPORTS"]
    inclines = ["// GENERATED by tools/gen_proxy_exports.py -- do not edit.",
                f"// Reference: {a.dll}",
                "// UBW_EXPORT(index, ordinal, name) -- name is nullptr for ordinal-only exports."]
    for idx, (ordinal, name) in enumerate(exports):
        stub = f"ubw_stub_{ordinal}"
        if name:
            deflines.append(f"    {name}={stub} @{ordinal}")
            inclines.append(f'UBW_EXPORT({idx}, {ordinal}, "{name}")')
        else:
            deflines.append(f"    {stub} @{ordinal} NONAME")
            inclines.append(f"UBW_EXPORT({idx}, {ordinal}, nullptr)")
    try:
        OUT_DEF.write_text("\n".join(deflines) + "\n")
        OUT_INC.write_text("\n".join(inclines) + "\n")
    except OSError as e:
        die(f"write failed: {e}")
    print(f"{len(exports)} exports ({sum(1 for _, n in exports if n)} named) -> {OUT_DEF.name}, {OUT_INC.name}")


if __name__ == "__main__":
    main()
